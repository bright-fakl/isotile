import numpy as np
import pytest

from isotile import IsohedralTiling, check_prototile, get_type, tiling_types

ALL_TYPES = tiling_types()


def random_tilings(number: int, n: int, spread: float, seed: int) -> list[IsohedralTiling]:
    """Up to ``n`` tilings of a type with parameters = defaults + uniform(-spread, spread); invalid draws are skipped."""
    rng = np.random.default_rng(seed + number)
    base = IsohedralTiling(number)
    out = []
    for _ in range(4 * n):
        if len(out) == n:
            break
        try:
            out.append(IsohedralTiling(number, base.parameters + rng.uniform(-spread, spread, len(base.parameters))))
        except ValueError:
            continue
    return out


@pytest.fixture(params=ALL_TYPES, ids=[f"IH{n}" for n in ALL_TYPES])
def number(request) -> int:
    return request.param


def curvable_ids(number: int) -> list[int]:
    """Shape ids of the type that are used by an edge and are not straight."""
    t = get_type(number)
    return [i for i in sorted(set(t.edge_shape_ids.tolist())) if t.shape_types[i] != "I"]


def random_curves(number: int, rng: np.random.Generator, amplitude: float) -> dict[int, np.ndarray]:
    """Random control points from (0, 0) to (1, 0) for each curvable shape id.

    J curves have 1 to 4 inner points with ascending x. U and S curves have 1 to 3 points in the first half
    (ascending x below 0.5), a middle point and the second half generated by the symmetry.
    """
    from isotile import enforce_symmetry

    t = get_type(number)
    out = {}
    for i in curvable_ids(number):
        if t.shape_types[i] == "J":
            m = int(rng.integers(1, 5))
            inner = np.column_stack([np.sort(rng.uniform(0.05, 0.95, m)), rng.uniform(-amplitude, amplitude, m)])
            out[i] = np.vstack([[0.0, 0.0], inner, [1.0, 0.0]])
        else:
            m = int(rng.integers(1, 4))
            first = np.column_stack([np.sort(rng.uniform(0.05, 0.45, m)), rng.uniform(-amplitude, amplitude, m)])
            middle = np.array([[0.5, rng.uniform(-amplitude, amplitude)]]) if rng.random() < 0.5 else np.empty((0, 2))
            raw = np.vstack([[0.0, 0.0], first, middle, np.zeros((m + 1, 2))])
            out[i] = enforce_symmetry(raw, t.shape_types[i])
    return out


def random_frame(rng: np.random.Generator, reflect: bool) -> np.ndarray:
    """Random similarity (2, 3), reflecting if asked."""
    a = rng.uniform(0, 2 * np.pi)
    s = rng.uniform(0.5, 3.0)
    linear = s * np.array([[np.cos(a), -np.sin(a)], [np.sin(a), np.cos(a)]])
    if reflect:
        linear = linear @ np.diag([1.0, -1.0])
    return np.column_stack([linear, rng.uniform(-3, 3, 2)])


def random_valid_curved_tiling(
    number: int, seed: int, amplitude: float = 0.25, frame: np.ndarray | None = None, mode: str = "spline"
) -> IsohedralTiling | None:
    """A tiling with random curves whose amplitude is reduced until the outline is valid.

    Returns None for a type without a curvable edge.
    """
    rng = np.random.default_rng(1000 * seed + number)
    base = random_tilings(number, 1, 0.1, seed=seed)[0]
    if not curvable_ids(number):
        return None
    curves = random_curves(number, rng, 1.0)
    for _ in range(40):
        scaled = {k: v * [1.0, amplitude] for k, v in curves.items()}
        modes = dict.fromkeys(scaled, mode)
        if check_prototile(number, base.parameters, edge_curves=scaled, edge_curve_modes=modes).valid:
            return IsohedralTiling(number, base.parameters, edge_curves=scaled, edge_curve_modes=modes, frame=frame)
        amplitude *= 0.6
    raise AssertionError("no valid curves found")
